#!/bin/bash
set -euo pipefail

repo_root=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)
build="$repo_root/image/build-image.sh"
stage="$repo_root/image/pi-gen/stage-cardputerzero-os/02-app-platform/01-run.sh"
compositor="$repo_root/image/pi-gen/stage-cardputerzero-os/01-compositor/01-run.sh"

grep -q 'scripts/build-appd.sh' "$build"
grep -q 'scripts/build-app-runtime.sh' "$build"
grep -q 'scripts/build-example-app.sh' "$build"
grep -q '02-app-platform/payload' "$build"
grep -q 'cp0-appd register-installed' "$stage"
grep -q 'app_account_id=20000' "$stage"
grep -q '"$app_account_id" -le 20063' "$stage"
grep -q 'cardputerzero-trust.conf' "$stage"
grep -q '/etc/cardputerzero/trust/store' "$stage"
grep -q 'cardputerzero-appd.socket cardputerzero-broker.socket' "$stage"
grep -q 'cardputerzero-networkd.socket' "$stage"
grep -q 'cp0-networkd' "$stage"
grep -q 'cp0-documentd' "$stage"
grep -q 'cardputerzero-documentd.socket' "$stage"
grep -q 'cp0-audiod' "$stage"
grep -q 'cardputerzero-audiod.socket' "$stage"
grep -q 'useradd --system --gid cp0-audio' "$stage"
grep -q 'cp0-camerad' "$stage"
grep -q 'cardputerzero-camerad.socket' "$stage"
grep -q 'useradd --system --gid cp0-camera' "$stage"
grep -q 'useradd --system --gid cp0-document' "$stage"
grep -q '/var/lib/cardputerzero/documents' "$stage"
grep -q 'useradd --system --gid cp0-network' "$stage"
grep -qx 'rpicam-apps-lite' "$repo_root/image/pi-gen/stage-cardputerzero-os/02-app-platform/00-packages-nr"
grep -q 'cp0-gpiod' "$stage"
grep -q 'cardputerzero-gpiod.socket' "$stage"
grep -q 'useradd --system --gid cp0-gpio' "$stage"
grep -q 'cardputerzero-gpio.conf' "$stage"
grep -q 'cp0-radiod' "$stage"
grep -q 'cardputerzero-radiod.socket' "$stage"
grep -q 'useradd --system --gid cp0-radio --groups spi' "$stage"
grep -q '/etc/cardputerzero/lora.conf' "$stage"
grep -q 'cp0-storaged' "$stage"
grep -q 'cardputerzero-storaged.socket' "$stage"
grep -q 'cp0-stored' "$stage"
grep -q 'cardputerzero-stored.socket' "$stage"
grep -q 'useradd --system --gid cp0-store --groups cp0-control' "$stage"
grep -q '/etc/cardputerzero/store.conf' "$stage"
grep -q 'cardputerzero-store.conf' "$stage"
grep -q 'useradd --system --gid cp0-storage' "$stage"
grep -q 'cp0-storage -g cp0-storage -m 0700' "$stage"
grep -q 'device-core-recovery' "$stage"
grep -q 'device-stability-monitor' "$stage"
grep -q 'chown -R root:root' "$stage"
if grep -q 'cp0-app-20000 -g cp0-app-20000 -m 0700' "$stage"; then
    echo "error: application data must not be mounted from an app-owned host directory" >&2
    exit 1
fi
grep -qx 'systemctl enable cardputerzero-compositor.service' "$compositor"
