#!/bin/bash
set -euo pipefail

repo_root=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)
service="$repo_root/appd/systemd/cardputerzero-appd.service"
control="$repo_root/appd/systemd/cardputerzero-appd.socket"
broker="$repo_root/appd/systemd/cardputerzero-broker.socket"
tmpfiles="$repo_root/appd/systemd/cardputerzero-appd.conf"
network_service="$repo_root/appd/systemd/cardputerzero-networkd.service"
network_socket="$repo_root/appd/systemd/cardputerzero-networkd.socket"
document_service="$repo_root/appd/systemd/cardputerzero-documentd.service"
document_socket="$repo_root/appd/systemd/cardputerzero-documentd.socket"
audio_service="$repo_root/appd/systemd/cardputerzero-audiod.service"
audio_socket="$repo_root/appd/systemd/cardputerzero-audiod.socket"
camera_service="$repo_root/appd/systemd/cardputerzero-camerad.service"
camera_socket="$repo_root/appd/systemd/cardputerzero-camerad.socket"
display_service="$repo_root/appd/systemd/cardputerzero-displayd.service"
display_socket="$repo_root/appd/systemd/cardputerzero-displayd.socket"
display_tmpfiles="$repo_root/appd/systemd/cardputerzero-display.conf"
connectivity_service="$repo_root/appd/systemd/cardputerzero-connectivityd.service"
connectivity_socket="$repo_root/appd/systemd/cardputerzero-connectivityd.socket"
connectivity_tmpfiles="$repo_root/appd/systemd/cardputerzero-connectivity.conf"
power_service="$repo_root/appd/systemd/cardputerzero-powerd.service"
power_socket="$repo_root/appd/systemd/cardputerzero-powerd.socket"
power_tmpfiles="$repo_root/appd/systemd/cardputerzero-power.conf"
provision_service="$repo_root/appd/systemd/cardputerzero-provisiond.service"
provision_socket="$repo_root/appd/systemd/cardputerzero-provisiond.socket"
provision_tmpfiles="$repo_root/appd/systemd/cardputerzero-provision.conf"
provision_apply="$repo_root/appd/systemd/cardputerzero-provision-apply.service"
ssh_generator="$repo_root/appd/systemd/cardputerzero-ssh-generator"
ssh_gate="$repo_root/appd/systemd/cardputerzero-ssh-gate.conf"
sshd_config="$repo_root/appd/systemd/cardputerzero-sshd.conf"
gpio_service="$repo_root/appd/systemd/cardputerzero-gpiod.service"
gpio_socket="$repo_root/appd/systemd/cardputerzero-gpiod.socket"
gpio_tmpfiles="$repo_root/appd/systemd/cardputerzero-gpio.conf"
radio_service="$repo_root/appd/systemd/cardputerzero-radiod.service"
radio_socket="$repo_root/appd/systemd/cardputerzero-radiod.socket"
radio_config="$repo_root/appd/lora.conf"
storage_service="$repo_root/appd/systemd/cardputerzero-storaged.service"
storage_socket="$repo_root/appd/systemd/cardputerzero-storaged.socket"
storage_tmpfiles="$repo_root/appd/systemd/cardputerzero-storage.conf"
store_service="$repo_root/appd/systemd/cardputerzero-stored.service"
store_socket="$repo_root/appd/systemd/cardputerzero-stored.socket"
store_tmpfiles="$repo_root/appd/systemd/cardputerzero-store.conf"
store_config="$repo_root/appd/store.conf"
device_policy="$repo_root/appd/device-policy.json"
production_device_policy="$repo_root/appd/device-policy-production.json"
appd_server="$repo_root/crates/cp0-appd/src/server.rs"
appd_lifecycle="$repo_root/crates/cp0-appd/src/lifecycle.rs"
storage_protocol="$repo_root/crates/cp0-storage-protocol/src/lib.rs"
storage_service_source="$repo_root/crates/cp0-storaged/src/lib.rs"

grep -q '^Requires=.*cardputerzero-appd.socket.*cardputerzero-broker.socket.*cardputerzero-networkd.socket' "$service"
grep -q '^Requires=.*cardputerzero-documentd.socket' "$service"
grep -q '^Requires=.*cardputerzero-audiod.socket' "$service"
grep -q '^Requires=.*cardputerzero-camerad.socket' "$service"
grep -q '^Requires=.*cardputerzero-gpiod.socket' "$service"
grep -q '^Requires=.*cardputerzero-radiod.socket' "$service"
grep -q '^Requires=.*cardputerzero-storaged.socket' "$service"
grep -qx 'ReadWritePaths=/var/lib/cardputerzero/registry /var/lib/cardputerzero/apps' "$service"
grep -qx 'RestrictAddressFamilies=AF_UNIX' "$service"
grep -qx 'SupplementaryGroups=cp0-wayland' "$service"
if grep -Eq '^SupplementaryGroups=.*cp0-storage' "$service"; then
    echo "error: appd must not gain direct access to application-private storage" >&2
    exit 1
fi
grep -qx 'MemoryDenyWriteExecute=yes' "$service"
grep -qx 'FileDescriptorName=control' "$control"
grep -qx 'SocketMode=0660' "$control"
grep -qx 'FileDescriptorName=broker' "$broker"
grep -qx 'SocketMode=0666' "$broker"
grep -qx 'Service=cardputerzero-appd.service' "$broker"
grep -qx 'd /run/cardputerzero-broker 0711 root root -' "$tmpfiles"
grep -qx 'd /run/cardputerzero-networkd 0755 root root -' "$tmpfiles"
grep -qx 'User=cp0-network' "$network_service"
grep -qx 'RestrictAddressFamilies=AF_UNIX AF_INET AF_INET6' "$network_service"
grep -qx 'NoNewPrivileges=yes' "$network_service"
grep -qx 'FileDescriptorName=network' "$network_socket"
grep -qx 'SocketMode=0600' "$network_socket"
grep -qx 'Service=cardputerzero-networkd.service' "$network_socket"
grep -qx 'd /run/cardputerzero-documentd 0755 root root -' "$tmpfiles"
grep -qx 'User=cp0-document' "$document_service"
grep -qx 'ProtectSystem=strict' "$document_service"
grep -qx 'PrivateDevices=yes' "$document_service"
grep -qx 'RestrictAddressFamilies=AF_UNIX' "$document_service"
grep -qx 'FileDescriptorName=documents' "$document_socket"
grep -qx 'SocketMode=0600' "$document_socket"
grep -qx 'Service=cardputerzero-documentd.service' "$document_socket"
grep -qx 'd /run/cardputerzero-audiod 0750 root cp0-audio-control -' "$tmpfiles"
grep -qx 'User=cp0-audio' "$audio_service"
grep -qx 'SupplementaryGroups=audio' "$audio_service"
grep -qx 'PrivateDevices=no' "$audio_service"
grep -qx 'DevicePolicy=closed' "$audio_service"
grep -qx 'DeviceAllow=char-alsa rw' "$audio_service"
grep -qx 'RestrictAddressFamilies=AF_UNIX' "$audio_service"
grep -qx 'FileDescriptorName=audio' "$audio_socket"
grep -qx 'SocketGroup=cp0-audio-control' "$audio_socket"
grep -qx 'SocketMode=0660' "$audio_socket"
grep -qx 'Service=cardputerzero-audiod.service' "$audio_socket"
grep -q 'trusted_output_uids.contains' "$repo_root/crates/cp0-audiod/src/lib.rs"
grep -q 'trusted_pcm_uids.contains' "$repo_root/crates/cp0-audiod/src/lib.rs"
grep -q 'c"DACL"' "$repo_root/crates/cp0-audiod/src/lib.rs"
grep -q 'c"DACR"' "$repo_root/crates/cp0-audiod/src/lib.rs"
grep -q 'c"Speaker"' "$repo_root/crates/cp0-audiod/src/lib.rs"
grep -qx 'd /run/cardputerzero-camerad 0755 root root -' "$tmpfiles"
grep -qx 'User=cp0-camera' "$camera_service"
grep -qx 'Wants=cardputerzero-camera-probe.service' "$camera_service"
grep -qx 'After=cardputerzero-camerad.socket cardputerzero-camera-probe.service' "$camera_service"
grep -qx 'SupplementaryGroups=video' "$camera_service"
grep -qx 'Nice=10' "$camera_service"
grep -qx 'CPUWeight=10' "$camera_service"
grep -qx 'PrivateDevices=no' "$camera_service"
grep -qx 'DevicePolicy=closed' "$camera_service"
grep -qx 'DeviceAllow=char-video4linux rw' "$camera_service"
grep -qx 'DeviceAllow=char-media rw' "$camera_service"
grep -qx 'DeviceAllow=char-dma_heap rw' "$camera_service"
grep -Fqx 'DeviceAllow=/dev/dma_heap/linux,cma rw' "$camera_service"
grep -qx 'DeviceAllow=/dev/dma_heap/default_cma_region rw' "$camera_service"
grep -qx 'DeviceAllow=/dev/dma_heap/system rw' "$camera_service"
grep -qx 'DeviceAllow=/dev/vchiq rw' "$camera_service"
grep -qx 'RestrictAddressFamilies=AF_UNIX AF_NETLINK' "$camera_service"
if grep -qx 'ProcSubset=pid' "$camera_service"; then
    echo 'camera broker must retain /proc/device-tree for libcamera discovery' >&2
    exit 1
fi
grep -qx 'LogRateLimitIntervalSec=30s' "$camera_service"
grep -qx 'LogRateLimitBurst=30' "$camera_service"
grep -qx 'FileDescriptorName=camera' "$camera_socket"
grep -qx 'SocketMode=0600' "$camera_socket"
grep -qx 'Service=cardputerzero-camerad.service' "$camera_socket"
grep -q 'jpeg-encoder = "=0.6.1"' \
    "$repo_root/crates/cp0-camerad/Cargo.toml"
grep -q 'DEFAULT_RPICAM_VID.*"/usr/bin/rpicam-vid"' \
    "$repo_root/crates/cp0-camerad/src/lib.rs"
grep -q '"--rotation"' "$repo_root/crates/cp0-camerad/src/lib.rs"
grep -q '"--framerate"' "$repo_root/crates/cp0-camerad/src/lib.rs"
grep -q '"1280"' "$repo_root/crates/cp0-camerad/src/lib.rs"
grep -q '"720"' "$repo_root/crates/cp0-camerad/src/lib.rs"
grep -q 'CP0_JPEG_DEVICE "/dev/video31"' \
    "$repo_root/crates/cp0-camerad/src/v4l2_jpeg.c"
grep -q 'V4L2_PIX_FMT_YUV420' "$repo_root/crates/cp0-camerad/src/v4l2_jpeg.c"
grep -q 'V4L2_PIX_FMT_JPEG' "$repo_root/crates/cp0-camerad/src/v4l2_jpeg.c"
grep -q 'encode_yuv420_jpeg_hardware' \
    "$repo_root/crates/cp0-camerad/src/lib.rs"
grep -q 'STREAM_REQUEST_TIMEOUT.*from_millis(50)' \
    "$repo_root/crates/cp0-camerad/src/lib.rs"
grep -q 'STREAM_STALL_DEADLINE.*from_millis(500)' \
    "$repo_root/crates/cp0-camerad/src/lib.rs"
grep -q 'STREAM_START_DEADLINE.*from_secs(20)' \
    "$repo_root/crates/cp0-camerad/src/lib.rs"
grep -q 'camera access requires the current foreground runtime' \
    "$repo_root/crates/cp0-appd/src/server.rs"
grep -q 'fn release(&self)' "$repo_root/crates/cp0-camerad/src/lib.rs"
grep -qx 'User=cp0-display' "$display_service"
grep -qx 'ExecStartPre=-+/usr/bin/systemd-tmpfiles --create /usr/lib/tmpfiles.d/cardputerzero-display.conf' "$display_service"
grep -qx 'PrivateDevices=yes' "$display_service"
grep -qx 'ProtectSystem=strict' "$display_service"
grep -qx 'ReadWritePaths=-/sys/class/backlight/backlight/brightness' "$display_service"
grep -qx 'RestrictAddressFamilies=AF_UNIX' "$display_service"
grep -qx 'FileDescriptorName=display' "$display_socket"
grep -qx 'SocketGroup=cp0-display-control' "$display_socket"
grep -qx 'SocketMode=0660' "$display_socket"
grep -qx 'Service=cardputerzero-displayd.service' "$display_socket"
grep -qx 'd /run/cardputerzero-displayd 0750 root cp0-display-control -' "$display_tmpfiles"
grep -qx 'z /sys/class/backlight/backlight/brightness 0660 root cp0-display -' "$display_tmpfiles"
grep -qx 'User=root' "$connectivity_service"
grep -qx 'ExecStart=/usr/libexec/cardputerzero/cp0-connectivityd serve' "$connectivity_service"
grep -qx 'NoNewPrivileges=yes' "$connectivity_service"
grep -qx 'ProtectSystem=strict' "$connectivity_service"
grep -qx 'RestrictAddressFamilies=AF_UNIX AF_NETLINK' "$connectivity_service"
grep -qx 'FileDescriptorName=connectivity' "$connectivity_socket"
grep -qx 'SocketGroup=cp0-connectivity-control' "$connectivity_socket"
grep -qx 'SocketMode=0660' "$connectivity_socket"
grep -qx 'Service=cardputerzero-connectivityd.service' "$connectivity_socket"
grep -qx 'd /run/cardputerzero-connectivityd 0750 root cp0-connectivity-control -' "$connectivity_tmpfiles"
grep -q 'trusted_uids.contains' "$repo_root/crates/cp0-connectivityd/src/lib.rs"
grep -q 'DEFAULT_NMCLI_PATH.*"/usr/bin/nmcli"' "$repo_root/crates/cp0-connectivityd/src/lib.rs"
grep -qx 'User=root' "$power_service"
grep -qx 'ExecStart=/usr/libexec/cardputerzero/cp0-powerd serve' "$power_service"
grep -qx 'NoNewPrivileges=yes' "$power_service"
grep -qx 'CapabilityBoundingSet=' "$power_service"
grep -qx 'ProtectSystem=strict' "$power_service"
grep -qx 'RestrictAddressFamilies=AF_UNIX' "$power_service"
grep -qx 'FileDescriptorName=power' "$power_socket"
grep -qx 'SocketGroup=cp0-power-control' "$power_socket"
grep -qx 'SocketMode=0660' "$power_socket"
grep -qx 'Service=cardputerzero-powerd.service' "$power_socket"
grep -qx 'd /run/cardputerzero-powerd 0750 root cp0-power-control -' "$power_tmpfiles"
grep -q 'trusted_uids.contains' "$repo_root/crates/cp0-powerd/src/lib.rs"
grep -q 'DEFAULT_SYSTEMCTL_PATH.*"/usr/bin/systemctl"' "$repo_root/crates/cp0-powerd/src/lib.rs"
grep -qx 'User=root' "$provision_service"
grep -qx 'MemoryMax=64M' "$provision_service"
grep -qx 'CapabilityBoundingSet=CAP_CHOWN CAP_NET_ADMIN' "$provision_service"
grep -qx 'AmbientCapabilities=CAP_CHOWN CAP_NET_ADMIN' "$provision_service"
grep -qx 'ProtectHome=no' "$provision_service"
grep -qx 'ProtectHostname=no' "$provision_service"
grep -qx 'ReadWritePaths=/var/lib/cardputerzero/provisioning /var/lib/extrausers /home /etc /etc/NetworkManager/system-connections' "$provision_service"
grep -qx 'ListenSequentialPacket=/run/cardputerzero-provisiond/provision.sock' "$provision_socket"
grep -qx 'SocketGroup=cp0-provision-control' "$provision_socket"
grep -qx 'SocketMode=0660' "$provision_socket"
grep -qx 'd /run/cardputerzero-provisiond 0750 root cp0-provision-control -' "$provision_tmpfiles"
grep -qx 'd /var/lib/cardputerzero/provisioning 0700 root root -' "$provision_tmpfiles"
grep -qx 'ConditionPathExists=/var/lib/cardputerzero/provisioning/complete' "$provision_apply"
grep -qx 'ReadWritePaths=/var/lib/cardputerzero/provisioning /etc' "$provision_apply"
grep -q 'provisioning/ssh-enabled' "$ssh_generator"
grep -q 'registry/developer-mode' "$ssh_generator"
grep -qx 'ConditionPathExists=/var/lib/cardputerzero/provisioning/complete' "$ssh_gate"
grep -qx 'ExecCondition=/usr/libexec/cardputerzero/ssh-access-allowed' "$ssh_gate"
grep -qx 'AllowGroups cp0-ssh cp0-developer-access' "$sshd_config"
grep -qx 'AuthorizedKeysFile /etc/cardputerzero/authorized_keys/%u' "$sshd_config"
grep -qx 'DisableForwarding yes' "$sshd_config"
grep -qx 'd /run/cardputerzero-gpiod 0755 root root -' "$tmpfiles"
grep -qx 'User=cp0-gpio' "$gpio_service"
grep -qx 'PrivateDevices=yes' "$gpio_service"
grep -qx 'ProtectSystem=strict' "$gpio_service"
grep -qx 'RestrictAddressFamilies=AF_UNIX' "$gpio_service"
grep -qx 'ReadWritePaths=/sys/class/leds/grove_fun/brightness' "$gpio_service"
grep -qx 'ReadWritePaths=/sys/class/leds/ext_usb_gpio_fun/brightness' "$gpio_service"
grep -qx 'ReadWritePaths=/sys/class/leds/grove_5v_out/brightness' "$gpio_service"
grep -qx 'ReadWritePaths=/sys/class/leds/ext_5v_out/brightness' "$gpio_service"
grep -qx 'FileDescriptorName=gpio' "$gpio_socket"
grep -qx 'SocketMode=0600' "$gpio_socket"
grep -qx 'Service=cardputerzero-gpiod.service' "$gpio_socket"
test "$(grep -c '^z /sys/class/leds/.* 0660 root cp0-gpio -$' "$gpio_tmpfiles")" -eq 4
grep -qx 'd /run/cardputerzero-radiod 0755 root root -' "$tmpfiles"
grep -qx 'User=cp0-radio' "$radio_service"
grep -qx 'SupplementaryGroups=spi' "$radio_service"
grep -qx 'PrivateDevices=no' "$radio_service"
grep -qx 'DevicePolicy=closed' "$radio_service"
grep -qx 'DeviceAllow=/dev/spidev0.1 rw' "$radio_service"
grep -qx 'RestrictAddressFamilies=AF_UNIX' "$radio_service"
grep -qx 'FileDescriptorName=radio' "$radio_socket"
grep -qx 'SocketMode=0600' "$radio_socket"
grep -qx 'Service=cardputerzero-radiod.service' "$radio_socket"
grep -qx 'enabled=false' "$radio_config"
grep -qx 'd /run/cardputerzero-storaged 0755 root root -' "$tmpfiles"
grep -qx 'User=cp0-storage' "$storage_service"
grep -qx 'PrivateDevices=yes' "$storage_service"
grep -qx 'ReadWritePaths=/var/lib/cardputerzero/data' "$storage_service"
grep -qx 'RestrictAddressFamilies=AF_UNIX' "$storage_service"
grep -qx 'FileDescriptorName=storage' "$storage_socket"
grep -qx 'SocketMode=0600' "$storage_socket"
grep -qx 'Service=cardputerzero-storaged.service' "$storage_socket"
grep -qx 'd /var/lib/cardputerzero/data 0700 cp0-storage cp0-storage -' "$storage_tmpfiles"
grep -q 'StorageCommand::Usage' "$storage_protocol"
grep -q 'StorageCommand::Usage => self' "$storage_service_source"
grep -q '\.usage(storage_request_id, &installed.app_id, storage_quota_bytes)' "$appd_server"
grep -q 'while unit_is_active(unit)?' "$appd_lifecycle"
if grep -Eq 'args\(\["--quiet", "wait", unit\]\)' "$appd_lifecycle"; then
    echo "error: appd runtime monitoring must support systemd without systemctl wait" >&2
    exit 1
fi
grep -qx 'd /run/cardputerzero-appd/store 0700 cp0-store cp0-store -' "$tmpfiles"
grep -qx 'd /run/cardputerzero-store 0750 root cp0-control -' "$tmpfiles"
grep -qx 'User=cp0-store' "$store_service"
grep -qx 'SupplementaryGroups=cp0-control' "$store_service"
grep -qx 'MemoryMax=40M' "$store_service"
grep -qx 'ProtectSystem=strict' "$store_service"
grep -qx 'ReadWritePaths=/var/lib/cardputerzero/store /run/cardputerzero-appd/store' "$store_service"
grep -qx 'RestrictAddressFamilies=AF_UNIX AF_INET AF_INET6 AF_NETLINK' "$store_service"
grep -qx 'FileDescriptorName=control' "$store_socket"
grep -qx 'SocketGroup=cp0-control' "$store_socket"
grep -qx 'SocketMode=0660' "$store_socket"
grep -qx 'Service=cardputerzero-stored.service' "$store_socket"
grep -qx 'd /var/lib/cardputerzero/store 0700 cp0-store cp0-store -' "$store_tmpfiles"
grep -qx 'd /var/lib/cardputerzero/store/packages 0700 cp0-store cp0-store -' "$store_tmpfiles"
grep -qx 'catalog_url=' "$store_config"
grep -qx 'metrics_url=' "$store_config"
grep -q 'cardputerzero-stored.socket' "$service"
jq -e '.store_auto_update_allowed == true' "$device_policy" >/dev/null
jq -e '.store_auto_update_allowed == true' "$production_device_policy" >/dev/null
jq -e '.store_metrics_allowed == true' "$device_policy" >/dev/null
jq -e '.store_metrics_allowed == true' "$production_device_policy" >/dev/null
if grep -Eq 'catalog_url=https?://' "$store_config"; then
    echo "error: product profile must not embed a store endpoint" >&2
    exit 1
fi
