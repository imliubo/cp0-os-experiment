#!/bin/bash
set -euo pipefail

repo_root=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)
service="$repo_root/appd/systemd/cardputerzero-appd.service"
control="$repo_root/appd/systemd/cardputerzero-appd.socket"
broker="$repo_root/appd/systemd/cardputerzero-broker.socket"
tmpfiles="$repo_root/appd/systemd/cardputerzero-appd.conf"
network_service="$repo_root/appd/systemd/cardputerzero-networkd.service"
network_socket="$repo_root/appd/systemd/cardputerzero-networkd.socket"
document_service="$repo_root/appd/systemd/cardputerzero-documentd.service"
document_socket="$repo_root/appd/systemd/cardputerzero-documentd.socket"
audio_service="$repo_root/appd/systemd/cardputerzero-audiod.service"
audio_socket="$repo_root/appd/systemd/cardputerzero-audiod.socket"

grep -q '^Requires=.*cardputerzero-appd.socket.*cardputerzero-broker.socket.*cardputerzero-networkd.socket' "$service"
grep -q '^Requires=.*cardputerzero-documentd.socket' "$service"
grep -q '^Requires=.*cardputerzero-audiod.socket' "$service"
grep -qx 'ReadWritePaths=/var/lib/cardputerzero/registry' "$service"
grep -qx 'RestrictAddressFamilies=AF_UNIX' "$service"
grep -qx 'SupplementaryGroups=cp0-wayland' "$service"
grep -qx 'FileDescriptorName=control' "$control"
grep -qx 'SocketMode=0660' "$control"
grep -qx 'FileDescriptorName=broker' "$broker"
grep -qx 'SocketMode=0666' "$broker"
grep -qx 'Service=cardputerzero-appd.service' "$broker"
grep -qx 'd /run/cardputerzero-broker 0711 root root -' "$tmpfiles"
grep -qx 'd /run/cardputerzero-networkd 0755 root root -' "$tmpfiles"
grep -qx 'User=cp0-network' "$network_service"
grep -qx 'RestrictAddressFamilies=AF_UNIX AF_INET AF_INET6' "$network_service"
grep -qx 'NoNewPrivileges=yes' "$network_service"
grep -qx 'FileDescriptorName=network' "$network_socket"
grep -qx 'SocketMode=0600' "$network_socket"
grep -qx 'Service=cardputerzero-networkd.service' "$network_socket"
grep -qx 'd /run/cardputerzero-documentd 0755 root root -' "$tmpfiles"
grep -qx 'User=cp0-document' "$document_service"
grep -qx 'ProtectSystem=strict' "$document_service"
grep -qx 'PrivateDevices=yes' "$document_service"
grep -qx 'RestrictAddressFamilies=AF_UNIX' "$document_service"
grep -qx 'FileDescriptorName=documents' "$document_socket"
grep -qx 'SocketMode=0600' "$document_socket"
grep -qx 'Service=cardputerzero-documentd.service' "$document_socket"
grep -qx 'd /run/cardputerzero-audiod 0755 root root -' "$tmpfiles"
grep -qx 'User=cp0-audio' "$audio_service"
grep -qx 'SupplementaryGroups=audio' "$audio_service"
grep -qx 'PrivateDevices=no' "$audio_service"
grep -qx 'DevicePolicy=closed' "$audio_service"
grep -qx 'DeviceAllow=char-alsa rw' "$audio_service"
grep -qx 'RestrictAddressFamilies=AF_UNIX' "$audio_service"
grep -qx 'FileDescriptorName=audio' "$audio_socket"
grep -qx 'SocketMode=0600' "$audio_socket"
grep -qx 'Service=cardputerzero-audiod.service' "$audio_socket"
