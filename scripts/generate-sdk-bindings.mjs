#!/usr/bin/env node

import fs from "node:fs";
import path from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const contractPath = path.join(root, "sdk/abi/cardputerzero-hostcalls-v1.json");
const contract = JSON.parse(fs.readFileSync(contractPath, "utf8"));
const checkOnly = process.argv.slice(2).includes("--check");

const typeMap = {
  i32: { c: "int32_t", rust: "i32", wamr: "i" },
  u32: { c: "uint32_t", rust: "u32", wamr: "i" },
  i64: { c: "int64_t", rust: "i64", wamr: "I" },
  u64: { c: "uint64_t", rust: "u64", wamr: "I" },
  result: { c: "cp0_result_t", rust: "i32", wamr: "i" },
  "const-u8-ptr": { c: "const uint8_t *", rust: "*const u8", wamr: "*" },
  "mut-u8-ptr": { c: "uint8_t *", rust: "*mut u8", wamr: "*" },
  "const-rect-ptr": {
    c: "const cp0_rect_t *",
    rust: "*const crate::display::Rect",
    wamr: "*",
  },
  "mut-key-event-ptr": {
    c: "cp0_key_event_t *",
    rust: "*mut u8",
    wamr: "*",
  },
};

function fail(message) {
  throw new Error(`ABI contract: ${message}`);
}

function validateIdentifier(value, label) {
  if (typeof value !== "string" || !/^[a-z_][a-z0-9_]*$/.test(value))
    fail(`${label} is not a C identifier`);
}

function validateContract() {
  if (contract.schema_version !== 1 || contract.abi_version !== "1.0")
    fail("unsupported schema or ABI version");
  if (contract.module !== "cardputerzero" || !Array.isArray(contract.imports))
    fail("invalid module or imports");
  const names = new Set();
  const cNames = new Set();
  const witNames = new Set();
  for (const entry of contract.imports) {
    validateIdentifier(entry.name, "import name");
    validateIdentifier(entry.runtime_function, `${entry.name} runtime function`);
    validateIdentifier(entry.c_name, `${entry.name} C function`);
    if (names.has(entry.name) || cNames.has(entry.c_name) || witNames.has(entry.wit))
      fail(`duplicate import, C function or WIT mapping at ${entry.name}`);
    names.add(entry.name);
    cNames.add(entry.c_name);
    witNames.add(entry.wit);
    if (!(entry.result in typeMap) || !Array.isArray(entry.parameters))
      fail(`invalid result or parameters for ${entry.name}`);
    if (!Number.isSafeInteger(entry.native_fallback))
      fail(`invalid native fallback for ${entry.name}`);
    const parameterNames = new Set();
    for (const parameter of entry.parameters) {
      validateIdentifier(parameter.name, `${entry.name} parameter`);
      if (!(parameter.type in typeMap) || parameterNames.has(parameter.name))
        fail(`invalid or duplicate parameter for ${entry.name}`);
      parameterNames.add(parameter.name);
    }
    validateWamrSignature(entry);
    if (
      typeof entry.wit !== "string" ||
      !/^[a-z][a-z0-9-]*\.[a-z][a-z0-9-]*$/.test(entry.wit)
    )
      fail(`invalid WIT mapping for ${entry.name}`);
  }
}

function validateWamrSignature(entry) {
  const expectedParameters = [];
  for (let index = 0; index < entry.parameters.length; index += 1) {
    const parameter = entry.parameters[index];
    expectedParameters.push(typeMap[parameter.type].wamr);
    if (parameter.type.endsWith("-ptr")) {
      const length = entry.parameters[index + 1];
      if (!length || length.type !== "u32")
        fail(`${entry.name} pointer is not followed by a u32 bound`);
      expectedParameters.push("~");
      index += 1;
    }
  }
  const expected = `(${expectedParameters.join("")})${typeMap[entry.result].wamr}`;
  if (entry.wamr_signature !== expected)
    fail(`${entry.name} signature ${entry.wamr_signature} should be ${expected}`);
}

function parameters(entry, language, native = false) {
  if (entry.parameters.length === 0) return language === "c" ? "void" : "";
  return entry.parameters
    .map((parameter) => {
      const name = native ? `_${parameter.name}` : parameter.name;
      return `${name}: ${typeMap[parameter.type].rust}`;
    })
    .join(", ");
}

function cParameters(entry) {
  if (entry.parameters.length === 0) return "void";
  return entry.parameters
    .map((parameter) => `${typeMap[parameter.type].c}${typeMap[parameter.type].c.endsWith("*") ? "" : " "}${parameter.name}`)
    .join(", ");
}

function generateC() {
  const lines = [
    "/* Generated by scripts/generate-sdk-bindings.mjs. Do not edit. */",
    "#ifndef CARDPUTERZERO_GENERATED_IMPORTS_H",
    "#define CARDPUTERZERO_GENERATED_IMPORTS_H",
    "",
  ];
  for (const entry of contract.imports) {
    lines.push(`CP0_IMPORT(\"${entry.name}\")`);
    lines.push(`${typeMap[entry.result].c} ${entry.c_name}(${cParameters(entry)});`);
    lines.push("");
  }
  lines.push("#endif", "");
  return lines.join("\n");
}

function generateRust() {
  const lines = [
    "// Generated by scripts/generate-sdk-bindings.mjs. Do not edit.",
    "",
    "#[rustfmt::skip]",
    "#[cfg(target_arch = \"wasm32\")]",
    "mod target {",
    `    #[link(wasm_import_module = \"${contract.module}\")]`,
    "    unsafe extern \"C\" {",
  ];
  for (const entry of contract.imports) {
    lines.push(`        #[link_name = \"${entry.name}\"]`);
    lines.push(
      `        fn raw_${entry.name}(${parameters(entry, "rust")}) -> ${typeMap[entry.result].rust};`,
    );
  }
  lines.push("    }", "");
  for (const entry of contract.imports) {
    const callArguments = entry.parameters.map((parameter) => parameter.name).join(", ");
    lines.push(
      `    pub(crate) fn ${entry.name}(${parameters(entry, "rust")}) -> ${typeMap[entry.result].rust} {`,
      `        unsafe { raw_${entry.name}(${callArguments}) }`,
      "    }",
      "",
    );
  }
  lines.push(
    "}",
    "",
    "#[rustfmt::skip]",
    "#[cfg(not(target_arch = \"wasm32\"))]",
    "mod target {",
  );
  for (const entry of contract.imports) {
    lines.push(
      `    pub(crate) const fn ${entry.name}(${parameters(entry, "rust", true)}) -> ${typeMap[entry.result].rust} {`,
      `        ${entry.native_fallback}`,
      "    }",
      "",
    );
  }
  lines.push("}", "", "pub(crate) use target::*;", "");
  return lines.join("\n");
}

function generateRuntime() {
  const lines = ["/* Generated by scripts/generate-sdk-bindings.mjs. Do not edit. */"];
  for (const entry of contract.imports) {
    lines.push(
      `{\"${entry.name}\", (void *)${entry.runtime_function}, \"${entry.wamr_signature}\", NULL},`,
    );
  }
  lines.push("");
  return lines.join("\n");
}

function witFunctions(source) {
  const functions = new Set();
  const interfacePattern = /\binterface\s+([a-z][a-z0-9-]*)\s*\{/g;
  for (let match = interfacePattern.exec(source); match !== null; match = interfacePattern.exec(source)) {
    const interfaceName = match[1];
    let depth = 1;
    let cursor = interfacePattern.lastIndex;
    for (; cursor < source.length && depth > 0; cursor += 1) {
      if (source[cursor] === "{") depth += 1;
      if (source[cursor] === "}") depth -= 1;
    }
    if (depth !== 0) fail(`unterminated WIT interface ${interfaceName}`);
    const body = source.slice(interfacePattern.lastIndex, cursor - 1);
    const functionPattern = /\b([a-z][a-z0-9-]*)\s*:\s*func\s*\(/g;
    for (let functionMatch = functionPattern.exec(body); functionMatch !== null; functionMatch = functionPattern.exec(body))
      functions.add(`${interfaceName}.${functionMatch[1]}`);
    interfacePattern.lastIndex = cursor;
  }
  return functions;
}

function validateWit() {
  const source = fs.readFileSync(path.join(root, "sdk/wit/cardputerzero-sdk.wit"), "utf8");
  if (!source.startsWith(`package cardputerzero:sdk@${contract.abi_version}.0;`))
    fail("WIT package version does not match flat ABI version");
  const actual = witFunctions(source);
  const mapped = new Set(contract.imports.map((entry) => entry.wit));
  for (const name of mapped) if (!actual.has(name)) fail(`WIT function ${name} is missing`);
  for (const name of actual) {
    if (
      !name.startsWith("application.") &&
      !name.startsWith("lifecycle.") &&
      !mapped.has(name)
    )
      fail(`WIT function ${name} has no flat ABI mapping`);
  }
}

function update(relativePath, contents) {
  const destination = path.join(root, relativePath);
  if (checkOnly) {
    if (!fs.existsSync(destination) || fs.readFileSync(destination, "utf8") !== contents)
      fail(`${relativePath} is stale; run scripts/generate-sdk-bindings.mjs`);
    return;
  }
  fs.mkdirSync(path.dirname(destination), { recursive: true });
  fs.writeFileSync(destination, contents);
}

validateContract();
validateWit();
update("sdk/c/include/cardputerzero_imports.h", generateC());
update("sdk/rust/src/host_imports.rs", generateRust());
update("app-runtime/src/hostcall_symbols.inc", generateRuntime());
